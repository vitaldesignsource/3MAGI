#!/usr/bin/env node
// Writes src/data/gatedSlugs.generated.js — the list of essays whose text the
// client must request from the server instead of expecting in the bundle.
//
// Runs BEFORE `vite build`, because the client imports this file. Its sibling
// split-essays.mjs runs AFTER the build, because vite empties the output
// directory and would delete the essays otherwise.

import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, '..');
const gatedDir = path.join(webRoot, 'src/data/articles/gated');
const freeDir = path.join(webRoot, 'src/data/articles');

const gated = readdirSync(gatedDir).filter((f) => f.endsWith('.js')).map((f) => f.replace(/\.js$/, ''));
const free = readdirSync(freeDir).filter((f) => f.endsWith('.js')).map((f) => f.replace(/\.js$/, ''));

// A slug in both directories would be bundled AND gated — the bundled copy
// would leak the very text the gate exists to protect.
const both = gated.filter((s) => free.includes(s));
if (both.length) {
    throw new Error(`essay(s) present in BOTH articles/ and articles/gated/: ${both.join(', ')} — the bundled copy would leak the gated text`);
}

gated.sort();

writeFileSync(
    path.join(webRoot, 'src/data/gatedSlugs.generated.js'),
    '// GENERATED by tools/gated-manifest.mjs — do not edit.\n' +
    '// Slugs whose text lives on the server, not in this bundle. The client\n' +
    '// uses this only to know it must ask api/essay.php; it grants nothing.\n' +
    `export const gatedSlugs = new Set(${JSON.stringify(gated, null, 4)});\n`,
    'utf8'
);

console.log(`manifest: ${gated.length} gated, ${free.length} free`);
